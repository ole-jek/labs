void shiftStarsInRow(char row[], int length)
{
    int starCount = 0;
    // считаем количество звездочек в строке
    for (int i = 0; i < length; ++i) {
        if (row[i] == '*') {
            ++starCount;
        }
    }
    // заполняем сначала звездочками
    for (int i = 0; i < starCount; ++i) {
        row[i] = '*';
    }
    // заполняем оставшуюся часть подчеркиваниями
    for (int i = starCount; i < length; ++i) {
        row[i] = '_';
    }
}