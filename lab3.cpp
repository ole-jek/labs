void sorting(int* arr, int size)
{
    for (int i = 0; i < size - 1; ++i) {
        int maxind = i;
        for (int j = i + 1; j < size; ++j) {
            if (arr[j] > arr[maxind]) {
                maxind = j;
            }
        }
        swap(arr[i], arr[maxind]);
    }
}
